#!/usr/bin/env node
/**
 * Bundles `migrations/*.sql` into a TypeScript module.
 *
 * Why not fetch them at runtime or read them from disk?
 *   - Workers has no filesystem, so disk reads are impossible.
 *   - Fetching from R2 on cold start would add a network round-trip and a
 *     failure mode to the very first request of every deployment.
 * Inlining them costs a few KB and makes migration deterministic offline.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS_DIR = join(ROOT, 'migrations');
const OUT_FILE = join(ROOT, 'src', 'worker', 'db', 'migrations.generated.ts');

function main() {
  const files = readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort((a, b) => a.localeCompare(b, 'en'));

  if (files.length === 0) {
    console.error('[gen-migrations] No .sql files found in migrations/');
    process.exit(1);
  }

  const entries = files.map((file) => {
    const version = basename(file, '.sql');
    const sql = readFileSync(join(MIGRATIONS_DIR, file), 'utf8');
    return { version, sql };
  });

  const body = entries
    .map(
      ({ version, sql }) =>
        `  {\n    version: ${JSON.stringify(version)},\n    sql: ${JSON.stringify(sql)},\n  },`,
    )
    .join('\n');

  const out = `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.
// Run \`pnpm gen:migrations\` after changing anything in migrations/.

export interface BundledMigration {
  /** Filesystem-ordered identifier, e.g. "0001_init". */
  version: string;
  /** Raw SQL. Contains {{now}} / {{now_date}} placeholders for the dialect layer. */
  sql: string;
}

export const MIGRATIONS: readonly BundledMigration[] = [
${body}
];
`;

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, out, 'utf8');
  console.log(`[gen-migrations] Wrote ${entries.length} migration(s) to ${OUT_FILE}`);
}

main();